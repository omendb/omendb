//! Boundary cases shared by the raw OmenDB peer and the live PostgreSQL oracle.

pub struct Case {
    pub name: &'static str,
    pub before: &'static str,
    pub query: &'static str,
    pub status: u8,
    pub error: Option<&'static str>,
    pub completions: usize,
    pub controls: &'static [&'static str],
    pub committed_ids: &'static [i64],
}

